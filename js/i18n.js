  function t(key, lang) {
    const dict = translations[lang] || translations.bn;
    if (dict[key] !== undefined) return dict[key];
    return translations.en[key] !== undefined ? translations.en[key] : key;
  }

  function applyLang(lang) {
    if (!translations[lang]) lang = 'bn';

    document.documentElement.lang = lang;
    document.documentElement.dir = RTL_LANGS.includes(lang) ? 'rtl' : 'ltr';
    document.body.classList.toggle('rtl', RTL_LANGS.includes(lang));

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'), lang);
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.getAttribute('data-i18n-html'), lang);
    });

    const switcher = document.getElementById('langSwitcher');
    if (switcher) switcher.value = lang;

    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {
      /* localStorage unavailable — language just won't persist */
    }
  }

  function getStoredLang() {
    try {
      return localStorage.getItem(STORAGE_KEY) || 'bn';
    } catch (e) {
      return 'bn';
    }
  }

  function buildSwitcher() {
    const nav = document.querySelector('.site-links');
    if (!nav || document.getElementById('langSwitcher')) return;

    const select = document.createElement('select');
    select.id = 'langSwitcher';
    select.className = 'lang-switcher';
    select.setAttribute('aria-label', 'Language');

    Object.keys(LANG_NAMES).forEach((code) => {
      const opt = document.createElement('option');
      opt.value = code;
      opt.textContent = LANG_NAMES[code];
      select.appendChild(opt);
    });

    select.addEventListener('change', () => applyLang(select.value));
    nav.appendChild(select);
  }

  document.addEventListener('DOMContentLoaded', () => {
    buildSwitcher();
    applyLang(getStoredLang());
  });
